_SEX = {n: "м" for n in MALE}
_SEX.update({n: "ж" for n in FEMALE})


def sex_of(name: str) -> str:
    """Пол по имени; если имя незнакомо — грубая эвристика по окончанию."""
    s = _SEX.get(name)
    if s:
        return s
    return "ж" if name.endswith(("а", "я")) else "м"


def random_name(sex: str, rng: random.Random, exclude=None) -> str:
    pool = FEMALE if sex == "ж" else MALE
    opts = [n for n in pool if not exclude or n not in exclude] or pool
    return rng.choice(opts)


def random_surname(sex: str, rng: random.Random) -> str:
    base = rng.choice(SURNAMES)
    # женская форма: Кузнецов -> Кузнецова, Бондарь -> Бондарь (несклоняемые оставляем)
    if sex == "ж" and base.endswith(("ов", "ев", "ин", "ый", "ой")):
        if base.endswith(("ый", "ой")):
            return base[:-2] + "ая"
        return base + "а"
    return base


def random_nick(sex: str, rng: random.Random) -> str:
    return rng.choice(NICK_F if sex == "ж" else NICK_M)


def role_nick(role: str) -> str:
    return ROLE_NICK.get(role, "")


def identity(sex: str, role: str, rng: random.Random) -> tuple[str, str]:
    """Выдать (фамилию, прозвище). Прозвище: иногда по черте/внешности, иначе по
    ремеслу (если оно заметное), иначе пусто. Детерминировано от rng."""
    surname = random_surname(sex, rng)
    roll = rng.random()
    if roll < 0.35:
        nick = random_nick(sex, rng)
    elif roll < 0.70:
        nick = role_nick(role)
    else:
        nick = ""
    return surname, nick


def random_sex(rng: random.Random) -> str:
    return "ж" if rng.random() < 0.5 else "м"


def random_parents(rng: random.Random) -> tuple[str, str]:
    """Имена отца и матери (для предыстории жителя)."""
    return random_name("м", rng), random_name("ж", rng)


def verb(sex: str, male: str, female: str) -> str:
    """Согласование рода: verb('ж','ушёл','ушла') -> 'ушла'."""
    return female if sex == "ж" else male
