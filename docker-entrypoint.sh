#!/bin/sh
# Контейнер стартует от root (см. Dockerfile — USER больше не фиксирован на этапе сборки),
# чтобы этот скрипт успел поправить владельца /data ДО запуска сервера, а затем сам
# сбрасывает привилегии до непривилегированного pog через su-exec.
#
# Зачем: docker-compose.yml монтирует ./data:/data с ХОСТА. chown в Dockerfile (на этапе
# сборки образа) чинит владельца только СОБСТВЕННОГО каталога /data образа — при монтировании
# bind-volume'а он полностью перекрывается хостовым каталогом со своим, часто несовпадающим,
# владельцем (обычно root, если докер сам создал ./data при первом запуске). Контейнерный
# pogserver работал от uid 10001 (pog), не мог писать в /data — accounts.Store.save() и
# SaveTo() проваливались (первая — раньше молча, см. accounts/accounts.go), и каждый
# перезапуск контейнера («./manage.sh update») выглядел так, будто игрок каждый раз получает
# нового случайного персонажа: аккаунты и сохранение мира никогда реально не записывались на
# диск. Починка владельца здесь, на каждом старте, устраняет это независимо от того, кто и
# как создал ./data на хосте.
set -e
chown -R pog:pog /data 2>/dev/null || true
exec su-exec pog "$@"
