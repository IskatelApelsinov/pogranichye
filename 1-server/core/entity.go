// Пакет core — субстрат живого мира (блок 1.1, «как устроен мир»). Здесь НЕТ правил
// игры: только сущности, их свойства-компоненты и мир, который всё это держит. Правила
// (голод, старение, разум, экономика) живут отдельными системами в пакете sim — так
// их можно добавлять и переписывать, не трогая ядро. Это и есть «делаем под людей-
// разработчиков»: новый модуль = новый компонент + новая система, ядро не меняется.
//
// Философия, вытащенная из разбора мёртвого прототипа: у ВСЕГО есть свойства, и ничего
// из них не теряется. Сущность — это не «юнит с полями», а мешок компонентов; сколько
// нужно свойств, столько и навесил. Житель, предмет, дом, деревня — всё это сущности.
package core

import "encoding/json"

// ID — вечный уникальный номер сущности. Не переиспользуется: если житель умер, его id
// больше никому не достанется (иначе рушится тождество и ссылки друг на друга).
type ID uint64

// Component — одно свойство сущности (тело, нужды, разум, кошелёк...). Kind — ключ, под
// которым компонент лежит в сущности и в снимке. Добавить свойство миру = объявить
// структуру с методом Kind() и зарегистрировать её (registry.go). Ядро про неё не знает.
type Component interface {
	Kind() string
}

// Entity — сущность: вечный id и набор компонентов по их Kind.
type Entity struct {
	ID    ID
	Comps map[string]Component
}

// Add вешает/заменяет компонент. Возвращает саму сущность — удобно цепочкой.
func (e *Entity) Add(c Component) *Entity {
	e.Comps[c.Kind()] = c
	return e
}

// Has — есть ли у сущности такой компонент.
func (e *Entity) Has(kind string) bool {
	_, ok := e.Comps[kind]
	return ok
}

// Get возвращает компонент по ключу (или nil). Обычно удобнее типизированные
// помощники из components.go (Vitals(e), Ident(e) и т.п.).
func (e *Entity) Get(kind string) Component {
	return e.Comps[kind]
}

// Remove снимает компонент (сущность теряет свойство — например, перестала быть домом).
func (e *Entity) Remove(kind string) {
	delete(e.Comps, kind)
}

// --- сериализация одной сущности (для снимка мира) ---

// entityWire — проводной вид сущности: компоненты как {kind: сырой-json}. Так снимок
// ничего не теряет и не зависит от порядка полей.
type entityWire struct {
	ID    ID                         `json:"id"`
	Comps map[string]json.RawMessage `json:"comps"`
}
