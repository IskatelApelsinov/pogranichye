// Пакет arcane — магия по канону мира Ёф. Мана — невидимое вещество, разлитое в местах
// (core.SettlementC.Mana): где-то густо (место силы), где-то пусто (мёртвая зона). Маг копит ману
// в себе из поля и тратит на ПЛЕТЕНИЕ (узор, что держат в уме): провёл ману через узор верно —
// изменил мир. Настоящий предел не «что запрещено», а сколько СЛОЖНОСТИ ум способен удержать:
// сильнее эффект → тяжелее держать → растёт надрыв и шанс срыва, а сорванное плетение бьёт в
// опасную сторону (откат по самому магу). Архимаг силён не списком заклятий, а тем, что держит
// в уме то, от чего у новичка лопнули бы сосуды. Так «воображение + мана» — честная система.
//
// Здесь — чистая механика плетения (ёмкость/навык/кости решают исход). Какие заклятья и когда
// творить в неактивном окне — решает система магии в sim (лечение, оберег). Это тот же принцип:
// присутствие и намерение — из реальной логики, система лишь разрешает исход.
package arcane

import (
	"pogranichye/core"
	"pogranichye/dice"
)

func init() {
	core.Register("mage", func() core.Component { return &MageC{} })
}

// MageC — дар мага: запас маны в себе. Предел запаса и ёмкость ума выводим из навыка магии
// (растёт с практикой) прямо при плетении — так компонент минимален и ничего не рассинхронит.
type MageC struct {
	Mana float64 `json:"mana"` // сколько маны маг держит в себе сейчас
}

func (c *MageC) Kind() string { return "mage" }

func Mage(e *core.Entity) *MageC { c, _ := e.Get("mage").(*MageC); return c }

// MaxMana — предел личного запаса по навыку (чем опытнее, тем больше в себя вмещает).
func MaxMana(skill float64) float64 { return 10 + skill*1.2 }

// Capacity — сколько сложности ум удержит без надрыва (растёт с навыком). Плетение сложнее
// ёмкости рвётся тем вернее, чем сильнее перебор.
func Capacity(skill float64) float64 { return 4 + skill*0.5 }

// Refill — маг втягивает ману из поля места (плотность fieldMana). В месте силы наполняется
// быстро, в мёртвой зоне — еле-еле. Возвращает, сколько маны вытянуто из поля (поле на столько
// и просядет — тяжёлое колдовство истощает местность, рождая мёртвые зоны; это доберёт worldmut).
func (c *MageC) Refill(skill, fieldMana float64) float64 {
	if c == nil {
		return 0
	}
	max := MaxMana(skill)
	if c.Mana >= max {
		return 0
	}
	draw := 2.5 * fieldMana // сколько поле отдаёт за день (копится несколько дней до заклятья)
	if c.Mana+draw > max {
		draw = max - c.Mana
	}
	c.Mana += draw
	return draw
}

// Weave сплетает плетение заданной сложности. Тратит ману; если её мало — плетение рвётся впустую
// с лёгким откатом. Иначе исход решают ёмкость ума и навык: удержал — успех; сорвал — откат тем
// тяжелее, чем выше было перенапряжение (сорванное плетение «скашивает в опасную сторону»).
// Возвращает успех и урон-откат по магу (0 — без отката).
func (c *MageC) Weave(complexity, skill float64, s *dice.Stream) (ok bool, backfire float64) {
	if c == nil || complexity <= 0 {
		return true, 0
	}
	if c.Mana < complexity {
		c.Mana = 0
		return false, complexity * 0.1 // не хватило маны — узор распался, лёгкая отдача
	}
	c.Mana -= complexity
	strain := complexity / (Capacity(skill) + 1) // >1 — ум держит на пределе
	hold := 0.55 + skill/120 - (strain-1)*0.6
	if hold > 0.98 {
		hold = 0.98
	}
	if hold < 0.03 {
		hold = 0.03
	}
	if s.Chance(hold) {
		return true, 0
	}
	return false, complexity * (0.3 + 0.7*strain) // сорвалось — откат растёт с перенапряжением
}
